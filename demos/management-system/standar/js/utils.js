function stockLevel(p) {
  const pct = p.maxStock > 0 ? (p.stock / p.maxStock) * 100 : 0;
  if (p.stock <= 0) return { label: 'Habis', cls: 'danger', pct: 0, color: 'var(--danger)', locCls: 'out' };
  if (p.stock <= p.minStock) return { label: 'Menipis', cls: 'warning', pct: Math.max(pct, 8), color: 'var(--warning)', locCls: 'low' };
  return { label: 'Aman', cls: 'success', pct: Math.max(pct, 20), color: 'var(--success)', locCls: 'safe' };
}

function randWalk(start, n, minPct = 0.75, maxPct = 1.3, volatility = 0.18) {
  const out = [start];
  let cur = start;
  for (let i = 1; i < n; i++) {
    cur = Math.max(start * minPct, cur * (0.75 + Math.random() * (1.3 - 0.75 + volatility)));
    out.push(Math.round(cur));
  }
  return out;
}

function monthLabels(monthsBack = 6) {
  const out = [];
  const d = new Date();
  d.setDate(1);
  for (let i = monthsBack - 1; i >= 0; i--) {
    const t = new Date(d);
    t.setMonth(d.getMonth() - i);
    out.push(t.toLocaleDateString('id-ID', { month: 'short' }));
  }
  return out;
}